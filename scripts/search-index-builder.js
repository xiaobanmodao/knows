const crypto = require('crypto');
const adapters = require('./subject-adapters');
const { getSubjectIds } = require('../data/subject-manifest');

function flatten(values) {
  return values.flatMap((value) => (Array.isArray(value) ? flatten(value) : [value]));
}

function compactText(value, maxLength = 140) {
  const text = String(value || '').replace(/\s+/g, ' ').trim();
  return text.length > maxLength ? `${text.slice(0, maxLength - 1)}…` : text;
}

function uniqueTokens(...values) {
  const seen = new Set();
  return flatten(values)
    .map((value) => compactText(value, 80))
    .filter((value) => value && value.length <= 80)
    .filter((value) => {
      const key = value.toLowerCase();
      if (seen.has(key)) {
        return false;
      }
      seen.add(key);
      return true;
    })
    .slice(0, 24);
}

function makeEntry({
  refId,
  subjectId,
  type,
  containerId = '',
  focusId = '',
  title,
  subtitle,
  description,
  tags = [],
  tokens = [],
}) {
  const identity = focusId || refId;
  return {
    key: `${subjectId}:${type}:${identity}`,
    refId,
    subjectId,
    type,
    containerId,
    focusId,
    title: compactText(title),
    subtitle: compactText(subtitle),
    description: compactText(description),
    tags: uniqueTokens(tags).slice(0, 4),
    tokens: uniqueTokens(title, tags, tokens),
  };
}

function validateSubjectTokenBudget(entries, subjectId, {
  maxTokenChars,
  maxEntryTokenChars,
  maxSubjectTokenChars,
}) {
  const subjectEntries = entries.filter((entry) => entry.subjectId === subjectId);
  let totalTokenChars = 0;
  let maxEntryTokenCharsSeen = 0;
  let maxTokenCharsSeen = 0;

  subjectEntries.forEach((entry) => {
    const tokenLengths = (entry.tokens || []).map((token) => String(token).length);
    const entryTokenChars = tokenLengths.reduce((total, length) => total + length, 0);
    const entryMaxTokenChars = tokenLengths.length ? Math.max(...tokenLengths) : 0;
    if (entryMaxTokenChars > maxTokenChars) {
      throw new Error(`${entry.key} 单个 token 为 ${entryMaxTokenChars} 字，超过 ${maxTokenChars}`);
    }
    if (entryTokenChars > maxEntryTokenChars) {
      throw new Error(`${entry.key} 单条 token 共 ${entryTokenChars} 字，超过 ${maxEntryTokenChars}`);
    }
    totalTokenChars += entryTokenChars;
    maxEntryTokenCharsSeen = Math.max(maxEntryTokenCharsSeen, entryTokenChars);
    maxTokenCharsSeen = Math.max(maxTokenCharsSeen, entryMaxTokenChars);
  });

  if (totalTokenChars > maxSubjectTokenChars) {
    throw new Error(`${subjectId} 全科 token 共 ${totalTokenChars} 字，超过 ${maxSubjectTokenChars}`);
  }

  return {
    entryCount: subjectEntries.length,
    totalTokenChars,
    maxEntryTokenChars: maxEntryTokenCharsSeen,
    maxTokenChars: maxTokenCharsSeen,
  };
}

function buildSearchIndex() {
  const entries = adapters.flatMap((adapter) => adapter.buildSearchEntries(makeEntry));
  const keySet = new Set();
  entries.forEach((entry) => {
    if (keySet.has(entry.key)) {
      throw new Error(`Duplicate search key: ${entry.key}`);
    }
    keySet.add(entry.key);
  });

  const sourceHash = crypto.createHash('sha256').update(JSON.stringify(entries)).digest('hex');
  const subjectCounts = entries.reduce((counts, entry) => ({
    ...counts,
    [entry.subjectId]: (counts[entry.subjectId] || 0) + 1,
  }), {});

  return {
    meta: {
      version: 1,
      sourceHash,
      entryCount: entries.length,
      subjectCounts,
    },
    entries,
  };
}

function renderSearchIndexModule(index) {
  const subjectCodes = getSubjectIds();
  const typeCodes = ['unit', 'word', 'grammar', 'chapter', 'topic', 'knowledge', 'template'];
  const subjectMap = Object.fromEntries(subjectCodes.map((value, position) => [value, position]));
  const typeMap = Object.fromEntries(typeCodes.map((value, position) => [value, position]));
  const rows = index.entries.map((entry) => [
    entry.refId,
    subjectMap[entry.subjectId],
    typeMap[entry.type],
    entry.containerId,
    entry.focusId,
    entry.title,
    entry.subtitle,
    entry.description,
    entry.tags,
    entry.tokens,
  ]);
  return `// Generated by scripts/build-search-index.js. Do not edit manually.\nconst SEARCH_INDEX_META=${JSON.stringify(index.meta)};\nconst SUBJECT_CODES=${JSON.stringify(subjectCodes)};\nconst TYPE_CODES=${JSON.stringify(typeCodes)};\nconst SEARCH_INDEX_ROWS=${JSON.stringify(rows)};\nmodule.exports={SEARCH_INDEX_META,SUBJECT_CODES,TYPE_CODES,SEARCH_INDEX_ROWS};\n`;
}

module.exports = {
  buildSearchIndex,
  renderSearchIndexModule,
  validateSubjectTokenBudget,
};
