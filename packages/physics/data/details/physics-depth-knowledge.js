function getQuantity(key) {
  const quantity = QUANTITY_LIBRARY[key];
  if (!quantity) throw new Error(`未知物理量键：${key}`);
  return { key, ...quantity };
}

function getPhysicsKnowledgeDepth(chapter, item) {
  const quantityKeys = KNOWLEDGE_QUANTITIES[item.id];
  if (!quantityKeys) throw new Error(`物理补深缺少知识点映射：${item.id}`);

  const quantities = quantityKeys.map(getQuantity);
  const conditions = [
    ...(CHAPTER_CONDITIONS[chapter.id] || []),
    ...(EXTRA_CONDITIONS[item.id] || []),
  ];
  const directionRules = DIRECTION_RULES[item.id] || [];
  const unitNote = quantities.length
    ? quantities.map((quantity) => `${quantity.name} ${quantity.symbol}：${quantity.unit}`).join('；')
    : '本知识点以定性关系或过程判断为主，不直接代入物理量单位。';

  return {
    detailVersion: 2,
    quantities,
    conditions,
    directionRules,
    unitNote,
    formulaDetails: item.formula ? [{
      kind: /[=∝≈]/.test(item.formula) ? '公式与规律' : '定性规律',
      expression: item.formula,
      variables: quantities,
      conditions,
      unitNote,
    }] : [],
    review: {
      status: 'verified',
      reviewedAt: '2026-08-01',
      sourceKeys: ['moe-physics-2022', 'pep-physics-public'],
    },
  };
}

