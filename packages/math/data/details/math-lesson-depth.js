function buildMathLessonDepth() {
  return LESSON_DEPTH_SOURCE.reduce((map, [chapterId, title, condition, relation, why, connectionKey]) => {
    const id = getStableLessonId(chapterId, title);
    const formula = lessonFormulaMap[title];
    const connection = CONNECTIONS[connectionKey];

    if (!formula || !connection || !CHAPTER_CONDITIONS[chapterId]) {
      throw new Error(`数学补深配置不完整：${title}`);
    }

    map[id] = {
      detailVersion: 2,
      lessonId: id,
      searchTerms: [`${title.replace(/^\d+(?:\.\d+)?\s*/, '')}为什么成立`, connection.title, ...connection.keywords],
      conditions: [CHAPTER_CONDITIONS[chapterId], condition],
      derivations: [{
        title: '从已知到结论',
        steps: [formula.description, relation],
        conclusion: formula.formula,
      }],
      whyItWorks: [why],
      connections: [{ key: connectionKey, ...connection }],
      review: { ...REVIEW },
    };
    return map;
  }, {});
}

const MATH_LESSON_DEPTH = buildMathLessonDepth();

function getMathLessonDepth(lessonId) {
  return MATH_LESSON_DEPTH[lessonId] || null;
}

