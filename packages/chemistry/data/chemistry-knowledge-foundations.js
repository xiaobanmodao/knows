const { buildKnowledge } = require('./chemistry-builders');

function textSection(title, content) {
  return { type: 'text', title, content };
}

function exampleSection(title, scenario, steps, conclusion) {
  return { type: 'example', title, scenario, steps, conclusion };
}

function equationSection(equationId, title, equation, condition, phenomenon, interpretation, ratioNote) {
  return {
    type: 'equation',
    equationId,
    title,
    equation,
    condition,
    phenomenon,
    interpretation,
    ratioNote,
  };
}

function defineKnowledge(definition) {
  return buildKnowledge({
    ...definition,
    coverImage: `/assets/figures/generated/chemistry/topics/${definition.topicId}/cover.png`,
    sections: [
      ...definition.sections,
      {
        type: 'tip',
        title: '适用条件与学习边界',
        content: definition.boundary,
      },
    ],
  });
}

